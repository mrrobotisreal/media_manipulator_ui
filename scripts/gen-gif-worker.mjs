#!/usr/bin/env node
/**
 * Bundles Motion's GIF encoder Worker (ticket MM47 decision 2) into a string
 * constant, `lib/vector/raster/gifWorker.generated.ts` (checked in, "DO NOT
 * EDIT"), started at runtime from a Blob URL as a classic worker.
 *
 * Why not `new Worker(new URL('./gif.worker.ts', import.meta.url))`: Next 16's
 * Turbopack build emits that file as an untranspiled static asset
 * (`.next/static/media/gif.worker.<hash>.ts`), which a browser cannot run.
 * A pre-bundled string works with any bundler, has no extra request, and
 * mirrors `scripts/gen-anime-runtime.mjs` (MM45).
 *
 *   node scripts/gen-gif-worker.mjs           (write)
 *   node scripts/gen-gif-worker.mjs --check   (exit 1 when stale)
 *
 * `lib/vector/raster/gifWorker.test.ts` regenerates in memory and fails when
 * the checked-in file differs (an encoder change without a regeneration).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const ENTRY = join(ROOT, 'lib', 'vector', 'raster', 'gif.worker.ts');
export const OUT_FILE = join(ROOT, 'lib', 'vector', 'raster', 'gifWorker.generated.ts');

export async function render(root = ROOT) {
  const { build } = await import('esbuild');
  const result = await build({
    entryPoints: [join(root, 'lib', 'vector', 'raster', 'gif.worker.ts')],
    bundle: true,
    minify: true,
    format: 'iife',
    legalComments: 'none',
    target: 'es2019',
    platform: 'browser',
    write: false,
    absWorkingDir: root,
  });
  const code = result.outputFiles[0].text.trim();
  return [
    '// DO NOT EDIT. Generated by scripts/gen-gif-worker.mjs from lib/vector/raster/gif.worker.ts',
    '// (gifSession.ts + gifEncoder.ts, in-house). Regenerate after changing them: node scripts/gen-gif-worker.mjs',
    '',
    '/** The GIF encoder Worker, a minified classic-worker script (started from a Blob URL). */',
    `export const GIF_WORKER_SOURCE = ${JSON.stringify(code)};`,
    '',
  ].join('\n');
}

async function main() {
  const text = await render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT_FILE, 'utf8');
    } catch {
      /* missing */
    }
    if (current !== text) {
      console.error(`${OUT_FILE} is stale — run node scripts/gen-gif-worker.mjs`);
      process.exit(1);
    }
    console.log('gif worker up to date');
    return;
  }
  writeFileSync(OUT_FILE, text);
  console.log(`wrote ${OUT_FILE} (${text.length} bytes)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
