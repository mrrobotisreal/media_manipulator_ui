/**
 * Shared helpers for the code exporters (MM46: React/TSX, JS/TS module, and
 * later Dart): safe string literals, identifier and file names, the generated
 * file header, and the player source annotated for strict TypeScript.
 *
 * Rule for every code exporter: a string from the document (layer name, text,
 * project name, CSS, path data) only ever reaches the output through
 * `jsString` / `jsonLiteral` — never a template literal, never a comment.
 */
import { MOTION_BRAND } from '@/lib/vector/brand';
import { ANIME_LICENSE, ANIME_VERSION } from './animeRuntime.generated';
import { PLAYER_SOURCE } from './animePlayer';

/** A feature a code exporter could not carry over (shown in the export dialog). */
export interface CodeExportWarning {
  layerId: string;
  feature: string;
  reason: string;
}

/** Escape what could end a `<script>`/CDATA/comment or a JS line early: `<`, `>`, `&`, U+2028, U+2029. */
function escapeJsText(json: string): string {
  return json
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

/** A double-quoted JS/TS string literal that evaluates back to exactly `s`. */
export function jsString(s: string): string {
  return escapeJsText(JSON.stringify(s));
}

/** `value` as a JS expression (JSON, escaped like `jsString`). */
export function jsonLiteral(value: unknown): string {
  return escapeJsText(JSON.stringify(value));
}

/** Words reserved in JS/TS (incl. strict mode, module code and contextual keywords a class/function name must avoid). */
export const JS_RESERVED_WORDS: ReadonlySet<string> = new Set([
  'abstract', 'any', 'as', 'async', 'await', 'boolean', 'break', 'case', 'catch', 'class', 'const', 'constructor', 'continue',
  'debugger', 'declare', 'default', 'delete', 'do', 'else', 'enum', 'eval', 'export', 'extends', 'false', 'finally', 'for',
  'from', 'function', 'get', 'if', 'implements', 'import', 'in', 'instanceof', 'interface', 'is', 'keyof', 'let', 'module',
  'namespace', 'never', 'new', 'null', 'number', 'of', 'package', 'private', 'protected', 'public', 'readonly', 'require',
  'return', 'set', 'static', 'string', 'super', 'switch', 'symbol', 'this', 'throw', 'true', 'try', 'type', 'typeof',
  'undefined', 'unknown', 'var', 'void', 'while', 'with', 'yield', 'arguments',
]);

/** Globals/imports the generated files rely on; a component of that name would shadow them. */
const SHADOWING_NAMES: ReadonlySet<string> = new Set([
  'React', 'SVGProps', 'Math', 'JSON', 'String', 'Number', 'Object', 'Array', 'Date', 'Error', 'Symbol', 'Boolean',
  'Function', 'RegExp', 'Promise', 'Map', 'Set', 'Document', 'Element', 'DOMParser', 'SVGSVGElement', 'NaN', 'Infinity',
  'SPEC', 'SVG', 'JSX', 'AnimeApi',
]);

export function isReservedJsWord(word: string): boolean {
  return JS_RESERVED_WORDS.has(word) || JS_RESERVED_WORDS.has(word.toLowerCase());
}

/** An ASCII identifier that is not a JS/TS reserved word. */
export function isValidJsIdentifier(name: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !isReservedJsWord(name);
}

/**
 * A PascalCase identifier from a project name: ASCII letters and digits only,
 * words split on anything else. Empty, digit-leading or reserved results fall
 * back to `fallback` (plus the digits, when the name started with them).
 */
export function toPascalIdentifier(name: string, fallback: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter((w) => w.length > 0);
  const joined = words.map((w) => w[0].toUpperCase() + w.slice(1)).join('');
  let out = joined;
  if (out === '') out = fallback;
  else if (/^[0-9]/.test(out)) out = `${fallback}${out}`;
  if (!isValidJsIdentifier(out) || SHADOWING_NAMES.has(out)) out = `${out}${fallback}`;
  return isValidJsIdentifier(out) && !SHADOWING_NAMES.has(out) ? out : fallback;
}

/** A filesystem-safe base name (letters, digits, `-`, `_`). */
export function codeFileBase(name: string | undefined): string {
  const base = (name ?? '')
    .trim()
    .replace(/[^A-Za-z0-9_-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return base || 'animation';
}

/**
 * The header comment of a generated file (ticket decision 9): the generator
 * line, no date (deterministic), the runtime, and for anime.js the MIT notice.
 * `//` comments only, so no licence text can close a block comment.
 */
export function codeHeader(runtime: 'css' | 'anime'): string {
  const lines = [`// Generated by Media Manipulator ${MOTION_BRAND}`];
  if (runtime === 'css') {
    lines.push('// Runtime: CSS animations (no animation library needed).');
  } else {
    lines.push(`// Runtime: anime.js v${ANIME_VERSION} (https://animejs.com) — install: npm i animejs@${ANIME_VERSION}`);
    lines.push('//');
    for (const l of ANIME_LICENSE.split('\n')) lines.push(l === '' ? '//' : `// ${l}`);
  }
  return lines.join('\n');
}

/**
 * `PLAYER_SOURCE` with every parameter and `var` typed `any` and `runPlayer`
 * returning `any`, so it compiles under `strict`.
 */
export function typedPlayerSource(): string {
  const typed = PLAYER_SOURCE.replace(/function(\s+\w+)?\s*\(([^)]*)\)/g, (_m, nm: string | undefined, params: string) => {
    const list = params
      .split(',')
      .map((p) => p.trim())
      .filter((p) => p !== '')
      .map((p) => `${p}: any`)
      .join(', ');
    return `function${nm ?? ' '}(${list})`;
  });
  return typed
    .split('\n')
    .map((line) =>
      /\bvar\s/.test(line)
        ? line.replace(/\bvar\s+(\w+)(\s*[=,;])/, 'var $1: any$2').replace(/, (\w+) = /g, ', $1: any = ')
        : line,
    )
    .join('\n')
    .replace('function runPlayer(A: any, spec: any, root: any) {', 'function runPlayer(A: any, spec: any, root: any): any {');
}
