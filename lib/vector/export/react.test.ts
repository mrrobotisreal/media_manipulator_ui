/**
 * MM46: React/TSX exporter goldens, compile check, escaping and safety.
 *
 * Goldens: `__golden__/react/<name>.json` (input VectorDoc) → `<name>.tsx`
 * (expected bytes). Regenerate after an intended change with
 *
 *     UPDATE_GOLDEN=1 npx vitest run lib/vector/export/react.test.ts
 *
 * Every golden is compiled with the TypeScript API under `strict` + `react-jsx`.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';

import { MOTION_BRAND } from '@/lib/vector/brand';
import { parseVectorDoc, type VectorDoc } from '@/lib/vector/vectorTypes';
import { ANIME_LICENSE, ANIME_VERSION } from './animeRuntime.generated';
import { syntaxErrors, typecheck } from './codeCheck.testutil';
import { AnimeExportError } from './anime';
import { CssExportError } from './css';
import { exportReactComponent } from './react';

const DIR = join(__dirname, '__golden__', 'react');
const NAMES = readdirSync(DIR)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();
const UPDATE = process.env.UPDATE_GOLDEN === '1';

const load = (name: string): VectorDoc => {
  const r = parseVectorDoc(readFileSync(join(DIR, `${name}.json`), 'utf8'));
  if (!r.ok) throw new Error(`${name}: ${r.error}`);
  return r.doc;
};
const OPTS: Record<string, { name?: string }> = { 'hostile-names': { name: 'x"; </script> `${evil}` */ evil()' } };
const run = (name: string) => exportReactComponent(load(name), OPTS[name] ?? { name });

describe('React goldens (byte-exact)', () => {
  it('has the ticket goldens', () => {
    expect(NAMES).toEqual(['anime-morph', 'css-draw-on', 'css-transform', 'hostile-names']);
  });

  it.each(NAMES)('%s.tsx', (name) => {
    const out = run(name).code;
    const file = join(DIR, `${name}.tsx`);
    if (UPDATE || !existsSync(file)) writeFileSync(file, out);
    expect(out).toBe(readFileSync(file, 'utf8'));
  });
});

describe('React compile check', () => {
  it.each(NAMES)('%s.tsx compiles under strict TypeScript with zero diagnostics', (name) => {
    expect(typecheck(readFileSync(join(DIR, `${name}.tsx`), 'utf8'), 'react/__check__.tsx')).toEqual([]);
  });
});

describe('React output properties', () => {
  it.each(NAMES)('%s: header, licence, imports, no gsap, no dangerouslySetInnerHTML, deterministic', (name) => {
    const r = run(name);
    const lines = r.code.split('\n');
    expect(lines[0]).toBe(`// Generated by Media Manipulator ${MOTION_BRAND}`);
    expect(r.code).not.toMatch(/\d{4}-\d{2}-\d{2}/);
    const anime = r.runtime === 'anime';
    expect(r.code.includes(ANIME_LICENSE.split('\n')[0])).toBe(anime);
    expect(r.code.includes(`npm i animejs@${ANIME_VERSION}`)).toBe(anime);
    expect(r.code.includes("from 'animejs'")).toBe(anime);
    expect(/gsap/i.test(r.code)).toBe(false);
    expect(r.code).not.toContain('dangerouslySetInnerHTML');
    expect(exportReactComponent(load(name), OPTS[name] ?? { name }).code).toBe(r.code);
    expect([...r.code.matchAll(/from '([^']+)'/g)].map((m) => m[1]).every((m) => m === 'react' || m === 'animejs')).toBe(true);
  });

  it('chooses the runtime like chooseRuntime and names the file', () => {
    expect(run('css-transform')).toMatchObject({ runtime: 'css', reasons: [], fileName: 'css-transform.tsx' });
    expect(run('anime-morph')).toMatchObject({ runtime: 'anime', reasons: ['morph'] });
    expect(exportReactComponent(load('css-draw-on'), { name: 'Draw On', forceAnime: true })).toMatchObject({ runtime: 'anime', fileName: 'Draw-On.tsx' });
    expect(exportReactComponent(load('css-draw-on'), { name: 'draw on' }).code).toContain('export default function DrawOn(props: SVGProps<SVGSVGElement>)');
  });

  it('throws the shared export errors when the runtime cannot express the document', () => {
    const bad = { ...load('css-draw-on'), animations: [{ layerId: 'nope', property: 'opacity', keyframes: [{ t: 0, value: 1, easing: 'linear' }, { t: 100, value: 0, easing: 'linear' }] }] } as VectorDoc;
    expect(() => exportReactComponent(bad)).toThrow(CssExportError);
    expect(() => exportReactComponent(bad, { forceAnime: true })).toThrow(AnimeExportError);
  });

  it('converts attribute names to React props', () => {
    const code = run('css-transform').code;
    expect(code).toContain('xmlns={"http://www.w3.org/2000/svg"}');
    expect(code).toContain('viewBox=');
    expect(run('hostile-names').code).toMatch(/<rect[^\n]* data-name=\{"/);
    expect(code).not.toMatch(/ (stroke-width|stop-color|clip-path|class)=/);
    expect(code).toContain('<style>{styles}</style>');
  });

  it('camel-cases kebab attributes', () => {
    const doc = { ...load('css-draw-on') };
    const out = exportReactComponent(doc).code;
    expect(out).toContain('strokeWidth={"4"}');
    expect(out).toContain('strokeLinecap={"round"}');
    expect(out).toContain('strokeDasharray={"306.752"}');
  });
});

describe('React hostile names', () => {
  const r = run('hostile-names');
  const file = r.code; // byte-equal to the golden (tested above)

  it('parses with zero syntax diagnostics', () => {
    expect(syntaxErrors(r.code, ts.ScriptKind.TSX)).toEqual([]);
  });

  it('has no raw </script>, no raw < in literals and no line that starts with a name fragment', () => {
    expect(file).not.toContain('</script>');
    for (const line of file.split('\n')) {
      expect(line.trim()).not.toMatch(/^(evil|\*\/|\$\{|`|--|<\/?b>)/);
    }
    expect(file).not.toMatch(/^[ \t]*[^"\n]*`/m); // no template literal outside a double-quoted string
  });

  it('every attribute and text literal evaluates back to the document string', () => {
    const doc = load('hostile-names');
    const text = doc.layers.find((l) => l.type === 'text');
    const lits = [...file.matchAll(/\{("(?:[^"\\]|\\.)*")\}/g)].map((m) => JSON.parse(m[1]) as string);
    expect(text && 'text' in text && lits.includes(text.text)).toBe(true);
    const box = doc.layers[0];
    expect(lits.includes(box.type !== 'raw' && box.name ? box.name : '')).toBe(true);
  });

  it('skips raw layers with a warning', () => {
    expect(r.warnings).toEqual([{ layerId: 'opaque', feature: 'raw', reason: expect.any(String) }]);
    expect(file).not.toContain('inner');
  });

  it('turns the symbol-laden project name into a valid component and file name', () => {
    expect(r.fileName).toBe('x-script-evil-evil.tsx');
    expect(file).toMatch(/export default function XScriptEvilEvil\(/);
  });
});
