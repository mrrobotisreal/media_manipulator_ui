describe('Dart escaping', () => {
  const HOSTILE = [
    "'", '"', '$', '$x', '${x}', '\\', '\\n', '*/', '/*', 'a\nb', 'a\rb', 'a\tb', 'a\u2028b', 'a\u2029b', '\u0000', '\u0007', '\u007f',
    '</script>', ']]>', "'; evil(); '", '\\u{41}', 'Привет 😀', '', "it's $100 \\ ${'x'}",
  ];

  it.each(HOSTILE.map((s) => [JSON.stringify(s), s]))('dartString round-trips %s', (_label, input) => {
    const lit = dartString(input);
    expect(decodeDart(lit)).toBe(input);
    expect(lit).not.toMatch(/[\n\r\u2028\u2029]/);
    expect(lit).not.toContain('"""');
  });

  it('class names are valid, non-reserved ASCII identifiers', () => {
    const cases: Array<[string, string]> = [
      ['my cool-animation', 'MyCoolAnimation'],
      ['', 'AnimationWidget'],
      ['  ', 'AnimationWidget'],
      ['3d spinner', 'Animation3dSpinner'],
      ['class', 'ClassWidget'],
      ['Привет', 'AnimationWidget'],
      ["a'; $x ${y} */", 'AXY'],
      ['_private', 'Private'],
      ['state', 'StateWidget'],
      ['Widget', 'WidgetWidget'],
    ];
    for (const [input, expected] of cases) {
      const id = toDartIdentifier(input);
      expect(id).toBe(expected);
      expect(isValidDartIdentifier(id)).toBe(true);
    }
    expect(toDartIdentifier('State')).toBe('StateWidget');
    expect(toDartIdentifier('', 'Fallback')).toBe('Fallback');
  });

  it('file names are snake_case and filesystem-safe', () => {
    expect(dartFileName('My Cool-Animation')).toBe('my_cool_animation.dart');
    expect(dartFileName('SpinBox')).toBe('spin_box.dart');
    expect(dartFileName(undefined)).toBe('animation.dart');
    expect(dartFileName('../../etc/passwd')).toBe('etc_passwd.dart');
    expect(dartFileName('日本語')).toBe('animation.dart');
    expect(dartFileName('3d')).toBe('animation_3d.dart');
    expect(dartFileName('a'.repeat(200)).length).toBeLessThanOrEqual(65);
  });

  it('hostile layer names and text reach the golden only as escaped string literals', () => {
    const doc = load('hostile-names');
    const hostileName = (doc.layers[0] as { name: string }).name;
    for (const n of ['hostile-names', 'hostile-webview']) {
      const code = readFileSync(join(DIR, `${n}.dart`), 'utf8');
      // The class name was sanitised.
      expect(code).toMatch(n === 'hostile-names' ? /class XYZEvil(Widget)? extends/ : /class ClassWidget extends/);
      // Every line of code after the header is either plain code or a single-quoted literal list entry.
      const body = code.slice(code.indexOf('\nimport '));
      for (const line of body.split('\n')) {
        const m = /^ {2}('.*'),$/.exec(line);
        if (!m) continue;
        decodeDart(m[1]);
      }
      expect(body).not.toContain('\u2028');
      expect(body).not.toContain('\u0007');
      expect(body).not.toContain('\u007f');
    }
    // The native parts joined are the escaped static SVG, name included.
    const native = buildNativeModel(doc);
    expect(native.parts.join('')).toContain('data-name="he said &quot;hi&quot; ');
    expect(hostileName).toContain("'yo'");
    // And the literal that carries it round-trips.
    for (const part of native.parts) expect(decodeDart(dartString(part))).toBe(part);
  });

  it('the header contains no user string', () => {
    const code = run('hostile-names').code;
    const header = code.slice(0, code.indexOf('\nimport '));
    expect(header).not.toContain('evil');
    expect(header).not.toContain('he said');
    expect(header.split('\n').filter((l) => l !== '').every((l) => l.startsWith('//'))).toBe(true);
  });
});

