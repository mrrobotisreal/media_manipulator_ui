const f3 = (n: number) => formatNumber(n);

/** Line-by-line transcription of the Dart `_tf` (checked against `transformToAttr` through serializeSvg). */
function dartTf(b: number[]): string {
  const p: string[] = [];
  if (b[4] === 0 && b[5] === 0 && b[6] === 0 && b[2] === 1 && b[3] === 1) {
    if (f3(b[0]) !== '0' || f3(b[1]) !== '0') p.push(`translate(${f3(b[0])} ${f3(b[1])})`);
  } else {
    if (f3(b[0] + b[7]) !== '0' || f3(b[1] + b[8]) !== '0') p.push(`translate(${f3(b[0] + b[7])} ${f3(b[1] + b[8])})`);
    if (f3(b[4]) !== '0') p.push(`rotate(${f3(b[4])})`);
    if (f3(b[5]) !== '0') p.push(`skewX(${f3(b[5])})`);
    if (f3(b[6]) !== '0') p.push(`skewY(${f3(b[6])})`);
    if (f3(b[2]) !== '1' || f3(b[3]) !== '1') p.push(`scale(${f3(b[2])} ${f3(b[3])})`);
    if (f3(b[7]) !== '0' || f3(b[8]) !== '0') p.push(`translate(${f3(-b[7])} ${f3(-b[8])})`);
  }
  return p.length === 0 ? '' : ` transform="${p.join(' ')}"`;
}

/** The slots the Dart `_svgAt` computes at time t, using the player's semantics. */
function evalModel(m: NativeModel, t: number): Map<number, string> {
  const tt = Math.min(Math.max(0, t), m.duration);
  const groups = new Map(m.groups.map((g) => [g.slot, [...g.base]]));
  const out = new Map<number, string>();
  for (const c of m.channels) {
    let k = 0;
    while (k < c.segments.length - 1 && tt >= c.segments[k].t1) k++;
    const s = c.segments[k];
    let v: number | string;
    if (tt < s.t0) v = s.v0;
    else if (tt >= s.t1) v = s.v1;
    else {
      const u = (tt - s.t0) / (s.t1 - s.t0);
      const p = s.ease === 'linear' ? u : s.ease === 'hold' ? 0 : solveCubicBezier(s.ease, u);
      if (typeof s.v0 === 'number' && typeof s.v1 === 'number') v = Math.min(c.hi, Math.max(c.lo, s.v0 + (s.v1 - s.v0) * p));
      else {
        const a = parseColor(String(s.v0));
        const b = parseColor(String(s.v1));
        v = a && b ? formatColor(lerpColor(a, b, p)) : p < 1 ? s.v0 : s.v1;
      }
    }
    if (c.field >= 0) groups.get(c.slot)![c.field] = v as number;
    else out.set(c.slot, typeof v === 'number' ? f3(v) : v);
  }
  for (const [slot, b] of groups) out.set(slot, dartTf(b));
  return out;
}

const markupAt = (m: NativeModel, t: number): string => {
  const v = evalModel(m, t);
  return m.parts.map((p, i) => p + (i < m.parts.length - 1 ? (v.get(i) ?? '') : '')).join('');
};

describe('native model agrees with the sampler', () => {
  const natives = NAMES.filter((n) => n.startsWith('native-') || n === 'hostile-names');

  it.each(natives)('%s: the channel table holds exactly the trackPieces segments', (name) => {
    const doc = load(name);
    const m = buildNativeModel(doc);
    expect(m.channels.length).toBeGreaterThan(0);
    for (const c of m.channels) {
      const tr = doc.animations.filter((x) => x.layerId === c.layerId && x.property === c.property).pop()!;
      const pieces = trackPieces(tr, doc.duration);
      expect(c.segments).toHaveLength(pieces.length);
      pieces.forEach((p, i) => {
        const s = c.segments[i];
        expect([s.t0, s.t1]).toEqual([p.t0, p.t1].map((x) => Math.round(x * 1e6) / 1e6));
        const num = (v: number | string) => (typeof v === 'number' ? Math.round(v * 1e6) / 1e6 : v);
        if (typeof p.v0 === 'number') expect([s.v0, s.v1]).toEqual([num(p.v0), num(p.v1)]);
        const ease = p.timing.kind === 'linear' ? 'linear' : p.timing.kind === 'steps' ? 'hold' : p.timing.curve.map((x) => Math.round(x * 1e6) / 1e6);
        expect(s.ease).toEqual(ease);
      });
    }
  });

  it.each(natives)('%s: the parts joined with the frame-0 slot values equal serializeSvg(sampleDoc(doc, 0))', (name) => {
    const doc = load(name);
    const m = buildNativeModel(doc);
    expect(m.parts.length).toBeGreaterThan(1);
    expect(markupAt(m, 0)).toBe(serializeSvg(sampleDoc(doc, 0)));
  });

  it.each(natives)('%s: markup at many times equals serializeSvg(sampleDoc(doc, t))', (name) => {
    const doc = load(name);
    const m = buildNativeModel(doc);
    // Same text, numbers within one 3-decimal step (the table's easeBoth halves and the sampler's quadratic
    // differ by float noise, which can flip a rounding tie like 2.8125).
    const shape = (s: string) => s.replace(/-?\d+(\.\d+)?/g, '#');
    const nums = (s: string) => (s.match(/-?\d+(\.\d+)?/g) ?? []).map(Number);
    for (let t = 0; t <= doc.duration; t += 125) {
      const got = markupAt(m, t);
      const want = serializeSvg(sampleDoc(doc, t));
      expect(shape(got), `t=${t}`).toBe(shape(want));
      nums(got).forEach((n, i) => expect(Math.abs(n - nums(want)[i]), `t=${t} #${i}`).toBeLessThanOrEqual(0.0011));
    }
  });

  it('opacity and colours at several times equal the sampled layer', () => {
    const doc = load('native-colour');
    const m = buildNativeModel(doc);
    for (const t of [0, 250, 999, 1000, 1400, 2000]) {
      const sampled = sampleDoc(doc, t);
      const orb = sampled.layers[1] as { fill: string; strokeWidth: number };
      const svg = markupAt(m, t);
      expect(svg, `t=${t}`).toContain(`fill="${orb.fill}"`);
      expect(svg).toContain(`stroke-width="${f3(orb.strokeWidth)}"`);
    }
  });

  it('the Dart carries the doc loop flag and fps-quantised stepping', () => {
    expect(run('native-transform').code).toContain('_controller.repeat();');
    expect(run('native-colour').code).toContain('_controller.forward();');
    expect(run('native-colour').code).not.toContain('repeat()');
    expect(run('native-transform').code).toContain('const double _stepMs = 41.666667;');
  });
});

