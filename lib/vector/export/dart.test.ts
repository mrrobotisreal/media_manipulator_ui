/** Decoder for exactly the escapes `dartString` emits (and plain text). */
function decodeDart(lit: string): string {
  expect(lit.startsWith("'") && lit.endsWith("'")).toBe(true);
  const body = lit.slice(1, -1);
  let out = '';
  for (let i = 0; i < body.length; i++) {
    const ch = body[i];
    if (ch !== '\\') {
      expect(ch, 'raw quote / dollar / newline inside a literal').not.toMatch(/['$\n\r\u2028\u2029]/);
      out += ch;
      continue;
    }
    const n = body[++i];
    if (n === 'n') out += '\n';
    else if (n === 'r') out += '\r';
    else if (n === 't') out += '\t';
    else if (n === '\\' || n === "'" || n === '$') out += n;
    else if (n === 'u') {
      const m = /^\{([0-9A-F]+)\}/.exec(body.slice(i + 1));
      expect(m).not.toBeNull();
      out += String.fromCodePoint(parseInt(m![1], 16));
      i += m![0].length;
    } else throw new Error(`unexpected escape \\${n}`);
  }
  return out;
}

