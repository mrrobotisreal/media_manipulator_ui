/**
 * MM46: JS/TS module exporter goldens, parse + typecheck, and a jsdom run.
 *
 * Goldens: `__golden__/js/<name>.json` → `<name>.js` and `<name>.ts` (byte-exact).
 * Regenerate after an intended change with
 *
 *     UPDATE_GOLDEN=1 npx vitest run lib/vector/export/js.test.ts
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';
import { describe, expect, it, vi } from 'vitest';

import { MOTION_BRAND } from '@/lib/vector/brand';
import { parseVectorDoc, type VectorDoc } from '@/lib/vector/vectorTypes';
import { ANIME_LICENSE, ANIME_VERSION } from './animeRuntime.generated';
import { AnimeExportError } from './anime';
import { syntaxErrors, typecheck } from './codeCheck.testutil';
import { CssExportError } from './css';
import { exportJsModule } from './js';

const DIR = join(__dirname, '__golden__', 'js');
const NAMES = readdirSync(DIR)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();
const UPDATE = process.env.UPDATE_GOLDEN === '1';
const EXTS = ['js', 'ts'] as const;

const load = (name: string): VectorDoc => {
  const r = parseVectorDoc(readFileSync(join(DIR, `${name}.json`), 'utf8'));
  if (!r.ok) throw new Error(`${name}: ${r.error}`);
  return r.doc;
};
const run = (name: string, ext: (typeof EXTS)[number]) => exportJsModule(load(name), { typescript: ext === 'ts', name });
const CASES = NAMES.flatMap((n) => EXTS.map((e) => [n, e] as const));

describe('JS/TS goldens (byte-exact)', () => {
  it('has the ticket goldens', () => {
    expect(NAMES).toEqual(['anime-morph', 'css-transform', 'hostile-names']);
  });

  it.each(CASES)('%s.%s', (name, ext) => {
    const out = run(name, ext).code;
    const file = join(DIR, `${name}.${ext}`);
    if (UPDATE || !existsSync(file)) writeFileSync(file, out);
    expect(out).toBe(readFileSync(file, 'utf8'));
  });
});

describe('JS/TS parse and typecheck', () => {
  it.each(NAMES)('%s.js parses with zero syntax diagnostics', (name) => {
    expect(syntaxErrors(readFileSync(join(DIR, `${name}.js`), 'utf8'), ts.ScriptKind.JS)).toEqual([]);
  });

  it.each(NAMES)('%s.ts typechecks under strict TypeScript (dom + es2020) with zero diagnostics', (name) => {
    const code = readFileSync(join(DIR, `${name}.ts`), 'utf8');
    expect(typecheck(code, 'js/__check__.ts', { lib: ['lib.es2020.d.ts', 'lib.dom.d.ts'] })).toEqual([]);
  });
});

describe('JS/TS output properties', () => {
  it.each(CASES)('%s.%s: header, licence, imports, no gsap, deterministic, same API', (name, ext) => {
    const r = run(name, ext);
    expect(r.code.split('\n')[0]).toBe(`// Generated by Media Manipulator ${MOTION_BRAND}`);
    expect(r.code).not.toMatch(/\d{4}-\d{2}-\d{2}/);
    const anime = r.runtime === 'anime';
    expect(r.code.includes(ANIME_LICENSE.split('\n')[0])).toBe(anime);
    expect(r.code.includes(`npm i animejs@${ANIME_VERSION}`)).toBe(anime);
    expect(r.code.includes("from 'animejs'")).toBe(anime);
    expect(/gsap/i.test(r.code)).toBe(false);
    expect(r.code).not.toContain('innerHTML');
    expect(run(name, ext).code).toBe(r.code);
    for (const fn of ['mount', 'play', 'pause', 'seek']) expect(r.code).toContain(`export function ${fn}(`);
    expect(r.fileName).toBe(`${name}.${ext}`);
  });

  it('.js is the .ts minus type annotations', () => {
    const js = run('css-transform', 'js').code;
    const ts_ = run('css-transform', 'ts').code;
    expect(js).not.toMatch(/: (Element|number|void|SVGSVGElement)/);
    expect(ts_).toContain('export function mount(el: Element): SVGSVGElement');
    expect(ts_).toContain('export function seek(ms: number): void');
    expect(js).toContain('export function mount(el)');
  });

  it('chooses the runtime like chooseRuntime', () => {
    expect(run('css-transform', 'js')).toMatchObject({ runtime: 'css', reasons: [] });
    expect(run('anime-morph', 'js')).toMatchObject({ runtime: 'anime', reasons: ['morph'] });
    expect(exportJsModule(load('css-transform'), { typescript: false, forceAnime: true }).runtime).toBe('anime');
  });

  it('throws the shared export errors', () => {
    const bad = { ...load('css-transform'), animations: [{ layerId: 'nope', property: 'opacity', keyframes: [{ t: 0, value: 1, easing: 'linear' }, { t: 100, value: 0, easing: 'linear' }] }] } as VectorDoc;
    expect(() => exportJsModule(bad, { typescript: false })).toThrow(CssExportError);
    expect(() => exportJsModule(bad, { typescript: false, forceAnime: true })).toThrow(AnimeExportError);
  });
});

describe('JS/TS hostile names', () => {
  it.each(EXTS)('hostile-names.%s has no breakout and the SVG literal evaluates back to well-formed markup', (ext) => {
    const code = run('hostile-names', ext).code;
    expect(code).not.toContain('</script>');
    expect(code).not.toMatch(/^[ \t]*[^"\n]*`/m);
    const lits = [...code.matchAll(/^ {2}("(?:[^"\\]|\\.)*"),$/gm)].map((m) => JSON.parse(m[1]) as string);
    const svg = lits.join('\n');
    const parsed = new DOMParser().parseFromString(svg, 'image/svg+xml');
    expect(parsed.getElementsByTagName('parsererror').length).toBe(0);
    expect(parsed.querySelectorAll('script').length).toBe(0);
    const doc = load('hostile-names');
    const box = doc.layers[0];
    // XML attribute-value normalisation turns the raw newline into a space.
    expect(parsed.getElementById('box')?.getAttribute('data-name')).toBe(box.type !== 'raw' ? box.name?.replace(/\s/g, ' ') : undefined);
  });
});

describe('JS module in jsdom (css runtime)', () => {
  const load_ = () => {
    const src = readFileSync(join(DIR, 'css-transform.js'), 'utf8').replace(/^export /gm, '');
    return new Function(`${src}\nreturn { mount, play, pause, seek };`)() as {
      mount: (el: Element) => SVGSVGElement;
      play: () => void;
      pause: () => void;
      seek: (ms: number) => void;
    };
  };

  it('mount appends an <svg> with the layer ids; play/pause/seek drive getAnimations', () => {
    const m = load_();
    const host = document.createElement('div');
    const svg = m.mount(host);
    expect(host.firstElementChild).toBe(svg);
    expect(svg.tagName.toLowerCase()).toBe('svg');
    expect(svg.querySelector('#box')).not.toBeNull();
    expect(svg.querySelector('style')).not.toBeNull();

    const anim = { play: vi.fn(), pause: vi.fn(), currentTime: 0 };
    (svg as unknown as { getAnimations: () => unknown[] }).getAnimations = () => [anim];
    expect(() => {
      m.play();
      m.pause();
      m.seek(500);
    }).not.toThrow();
    expect(anim.play).toHaveBeenCalledTimes(1);
    expect(anim.pause).toHaveBeenCalledTimes(1);
    expect(anim.currentTime).toBe(500);

    const again = m.mount(host);
    expect(host.children.length).toBe(1);
    expect(host.firstElementChild).toBe(again);
  });

  it('transport before mount is a no-op', () => {
    const m = load_();
    expect(() => {
      m.play();
      m.pause();
      m.seek(1);
    }).not.toThrow();
  });
});
