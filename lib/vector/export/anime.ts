/**
 * `VectorDoc` → animated SVG driven by the inline MIT anime.js runtime
 * (ticket MM45 decision 9, design §3.3.3). Used when `chooseRuntime` says
 * CSS cannot express the document in every engine (path morph, stop offset,
 * SVG blur, motion-path rotation edge case), or when the user asks for it.
 *
 * File layout (deterministic; byte-golden-tested with the runtime replaced
 * by `ANIME_RUNTIME_PLACEHOLDER`):
 *
 *   <!--
 *   anime.js v<version> (https://animejs.com), bundled below unmodified
 *   except for tree-shaking and minification.
 *   <LICENSE.md verbatim: "The MIT License … Copyright (c) Julian Garnier …">
 *   -->
 *   <!-- Generated by Media Manipulator Motion -->      (or "made with")
 *   <svg …>
 *     …static markup = frame 0 (`sampleDoc(doc, 0)`), so a viewer that runs
 *      no script (an `<img>` tag) shows the first frame…
 *     <script><![CDATA[
 *   /*ANIME_RUNTIME*\/                               (the real runtime in files)
 *   <player function> (`PLAYER_SOURCE`)
 *   runPlayer(__mmAnime, <spec JSON>, document);
 *   ]]></script>
 *   </svg>
 *
 * The licence notice is the FIRST thing in the file and sits outside the
 * minified block, so no minifier or the browser can drop it (§4). The script
 * runs when the SVG is opened directly or inlined in HTML; inside `<img>`
 * scripts never run (the dialog says so).
 *
 * The animation itself is a `PlayerSpec` (`animePlayer.ts`): the exporter
 * cuts every track into the same exact pieces as the CSS exporter
 * (`trackPieces`: holds as `steps(1)`, easeIn / easeOut as their exact cubic
 * curves, easeBoth as two halves), and the player composes values the way
 * `sampleDoc` does. `css.test.ts`-style agreement tests (`anime.test.ts`) run
 * the real bundled anime.js against `sampleDoc`.
 */
