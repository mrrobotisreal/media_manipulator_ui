const r6 = (n: number) => Math.round(n * 1e6) / 1e6;

function segments(track: Track, duration: number, kind: PlayerChannel['kind']): PlayerSegment[] {
  return trackPieces(track, duration).map((p: Piece) => {
    let ease: PlayerSegment['ease'] = 'linear';
    if (p.timing.kind === 'steps') ease = 'hold';
    else if (p.timing.kind === 'cubic') ease = p.timing.curve.map(r6) as [number, number, number, number];
    // Shape pairs that do not morph hold (the sampler's rule).
    if (kind === 'path' && typeof p.v0 === 'string' && typeof p.v1 === 'string' && p.v0 !== p.v1 && !morphCompatible(p.v0, p.v1)) ease = 'hold';
    // Colours reach the player as `#rrggbb` / `rgba(…)` only (it parses nothing else); paints that are
    // not plain colours (`none`, `url(#…)`) stay as they are and hold.
    const norm = (v: number | string) => {
      if (typeof v === 'number') return r6(v);
      if (kind !== 'color') return v;
      const c = parseColor(v);
      return c ? formatColor(c) : v;
    };
    return { t0: r6(p.t0), t1: r6(p.t1), v0: norm(p.v0), v1: norm(p.v1), ease };
  });
}

function samplePath(d: string): PlayerPath | null {
  const m = measurePath(d);
  if (!m || m.length <= 0) return null;
  const n = Math.min(MAX_PATH_SAMPLES, Math.max(1, Math.ceil(m.length / PATH_SAMPLE_STEP)));
  const step = m.length / n;
  const pts: number[] = [];
  const ang: number[] = [];
  let prev: number | null = null;
  for (let i = 0; i <= n; i++) {
    const p = m.at(Math.min(m.length, i * step) - (i === n && m.closed ? 1e-9 : 0));
    pts.push(roundNum(p.x), roundNum(p.y));
    // Unwrap so linear interpolation between samples never spins the long way.
    let a = p.angle;
    if (prev !== null) a = prev + (((a - prev + 540) % 360) - 180);
    ang.push(roundNum(a));
    prev = a;
  }
  return { pts, ang, step: r6(step), length: r6(m.length), closed: m.closed };
}

const kindOf = (property: string): PlayerChannel['kind'] => {
  if (property === 'fill' || property === 'stroke' || /\.color$/.test(property)) return 'color';
  if (property === 'd') return 'path';
  return 'number';
};

/** The player spec of a document (exported for tests). */
export function buildAnimeSpec(doc: VectorDoc): PlayerSpec {
  const duration = doc.duration;
  const { ok } = addressable(doc);
  const transforms: PlayerTransform[] = [];
  const tfIndex = new Map<string, number>();
  const paths: PlayerPath[] = [];
  const channels: PlayerChannel[] = [];
  const claimed = new Set<string>();
  const claim = (k: string) => (claimed.has(k) ? false : (claimed.add(k), true));

  const transformOf = (id: string): number => {
    let i = tfIndex.get(id);
    if (i === undefined) {
      const l = findDocLayer(doc, id);
      const t = resolveTransform(l && l.type !== 'raw' ? l.transform : undefined);
      i = transforms.length;
      transforms.push({ el: id, base: [t.x, t.y, t.scaleX, t.scaleY, t.rotation, t.skewX, t.skewY, t.anchorX, t.anchorY].map(r6) as PlayerTransform['base'] });
      tfIndex.set(id, i);
    }
    return i;
  };

  for (const tr of doc.animations) {
    if (tr.keyframes.length === 0 || duration <= 0) continue;
    const layer = ok.get(tr.layerId);
    if (!layer || layer.type === 'raw') continue;
    const p = tr.property;
    if (p === 'mask' || p === 'clipPath') continue;
    if (isTransformProperty(p)) {
      transformOf(tr.layerId);
      if (!claim(`${tr.layerId}\u0000${p}`)) continue;
      channels.push({ el: tr.layerId, to: { transform: transformField(p) }, kind: 'number', segments: segments(tr, duration, 'number') });
      continue;
    }
    if (p === 'motionPath') {
      const d = motionPathData(doc, tr);
      const sampled = d ? samplePath(d) : null;
      if (!sampled || !claim(`${tr.layerId}\u0000motion`)) continue;
      const i = transformOf(tr.layerId);
      transforms[i].motion = { path: paths.length, autoOrient: motionExtras(tr).autoOrient === true };
      paths.push(sampled);
      channels.push({ el: tr.layerId, to: { motion: 1 }, kind: 'number', segments: segments(tr, duration, 'number') });
      continue;
    }
    const stop = parseStopProperty(p);
    if (stop) {
      const g = trackGradient(doc, tr);
      if (!g || stop.index >= g.stops.length || !claim(`stop\u0000${g.id}\u0000${p}`)) continue;
      const color = stop.field === 'color';
      channels.push({
        el: g.id,
        sub: ['stop', stop.index],
        to: { attr: color ? 'stop-color' : 'offset' },
        kind: color ? 'color' : 'number',
        segments: segments(tr, duration, color ? 'color' : 'number'),
        ...(color ? {} : { min: 0, max: 1 }),
      });
      continue;
    }
    if (p === 'filter.blur') {
      const fid = trackBlurFilter(doc, tr.layerId);
      if (!fid || !claim(`blur\u0000${fid}`)) continue;
      channels.push({ el: fid, sub: ['feGaussianBlur', 0], to: { attr: 'stdDeviation' }, kind: 'number', segments: segments(tr, duration, 'number'), min: 0 });
      continue;
    }
    if (!claim(`${tr.layerId}\u0000${p}`)) continue;
    if (p === 'd' && layer.type !== 'path') continue;
    const attr = { opacity: 'opacity', fill: 'fill', stroke: 'stroke', strokeWidth: 'stroke-width', strokeDashoffset: 'stroke-dashoffset', d: 'd' }[p];
    if (!attr) continue;
    const kind = kindOf(p);
    channels.push({
      el: tr.layerId,
      to: { attr },
      kind,
      segments: segments(tr, duration, kind),
      ...(p === 'opacity' ? { min: 0, max: 1 } : p === 'strokeWidth' ? { min: 0 } : {}),
    });
  }
  // Transform groups with no channel (a motion track alone still writes the transform).
  return { duration, loop: docLoops(doc), transforms, paths, channels };
}

/** JSON for inlining in a CDATA script: no `]]>`, no `</`, nothing an XML or HTML parser could end early on. */
function scriptJson(v: unknown): string {
  return JSON.stringify(v).replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026');
}

export interface AnimeExportOptions {
  /** Anonymous export: "made with Media Manipulator" (MM44 decision 7). */
  anonymous?: boolean;
  /** Goldens: the runtime replaced by `ANIME_RUNTIME_PLACEHOLDER`. */
  placeholderRuntime?: boolean;
}

/**
 * `exportAnimatedSvgAnime(doc) → string`. Throws `AnimeExportError` when
 * `canExportAnime(doc)` fails (the dialog checks first).
 */
export function exportAnimatedSvgAnime(doc: VectorDoc, opts: AnimeExportOptions = {}): string {
  const check = canExportAnime(doc);
  if (!check.ok) throw new AnimeExportError(check.issues);
  const spec = buildAnimeSpec(doc);
  const runtime = opts.placeholderRuntime ? ANIME_RUNTIME_PLACEHOLDER : ANIME_RUNTIME;
  const brand = opts.anonymous ? MADE_WITH_COMMENT : generatedComment();
  const svg = serializeSvg(sampleDoc(doc, 0));
  const script = [
    '  <script><![CDATA[',
    runtime,
    PLAYER_SOURCE,
    `runPlayer(__mmAnime, ${scriptJson(spec)}, document);`,
    ']]></script>',
  ].join('\n');
  if (script.slice(script.indexOf('<![CDATA[') + 9, script.lastIndexOf(']]>')).includes(']]>')) {
    throw new AnimeExportError([{ code: 'bad_value' }]);
  }
  const end = svg.lastIndexOf('</svg>');
  const body = end >= 0 ? `${svg.slice(0, end)}${script}\n</svg>\n` : `${svg.replace(/\/>\n$/, '>\n')}${script}\n</svg>\n`;
  return `${animeLicenseHeader()}\n${brand}\n${body}`;
}

/** Every layer id the spec addresses exists in the static markup (sanity for tests). */
export function specTargets(spec: PlayerSpec): string[] {
  return [...new Set([...spec.transforms.map((t) => t.el), ...spec.channels.map((c) => c.el)])];
}

/** All ids the static markup declares (tests). */
export function docElementIds(doc: VectorDoc): Set<string> {
  const ids = new Set<string>();
  forEachLayer(doc, (l) => ids.add(l.id));
  for (const g of doc.defs.gradients) ids.add(g.id);
  for (const f of doc.defs.filters) ids.add(f.id);
  return ids;
}
