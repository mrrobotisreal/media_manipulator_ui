/** Stands in for the runtime in goldens (ticket decision 10). */
export const ANIME_RUNTIME_PLACEHOLDER = '/*ANIME_RUNTIME*/';
/** Motion paths are sampled every this many user units of arc length (max `MAX_PATH_SAMPLES`). */
export const PATH_SAMPLE_STEP = 0.5;
export const MAX_PATH_SAMPLES = 4000;

/** The runtime licence header comment (decision 9, design §4). */
export function animeLicenseHeader(): string {
  return [
    '<!--',
    `anime.js v${ANIME_VERSION} (https://animejs.com), bundled below unmodified except for tree-shaking and minification.`,
    '',
    ANIME_LICENSE,
    '-->',
  ].join('\n');
}

export type AnimeExportIssueCode = 'missing_layer' | 'defs_layer' | 'bad_value' | 'zero_duration';
export interface AnimeExportIssue {
  code: AnimeExportIssueCode;
  layerId?: string;
  property?: string;
}
export type AnimeExportCheck = { ok: true } | { ok: false; issues: AnimeExportIssue[] };

export class AnimeExportError extends Error {
  readonly issues: AnimeExportIssue[];
  constructor(issues: AnimeExportIssue[]) {
    super(`animated SVG (anime.js) cannot export: ${issues.map((i) => i.code).join(', ')}`);
    this.name = 'AnimeExportError';
    this.issues = issues;
  }
}

/** Layers the player can address by id (the tree, mask and clip contents; not symbol contents). */
function addressable(doc: VectorDoc): { ok: Map<string, Layer>; symbol: Set<string> } {
  const ok = new Map<string, Layer>();
  const symbol = new Set<string>();
  const walk = (ls: Layer[], into: (l: Layer) => void) => {
    for (const l of ls) {
      into(l);
      if (l.type === 'group') walk(l.children, into);
    }
  };
  walk(doc.layers, (l) => ok.set(l.id, l));
  for (const m of doc.defs.masks) walk(m.layers, (l) => ok.set(l.id, l));
  for (const c of doc.defs.clipPaths) walk(c.layers, (l) => ok.set(l.id, l));
  for (const s of doc.defs.symbols) walk(s.layers, (l) => symbol.add(l.id));
  return { ok, symbol };
}

const PATH_DATA = /^[MLCQAZmlcqaz0-9eE.,+\-\s]*$/;

function valueOk(property: string, v: number | string): boolean {
  if (property === 'fill' || property === 'stroke') return typeof v === 'string' && isSafePaint(v);
  if (/^gradientStop\[\d+\]\.color$/.test(property)) return typeof v === 'string' && isSafeColor(v);
  if (property === 'd') return typeof v === 'string' && PATH_DATA.test(v);
  return typeof v === 'number' && Number.isFinite(v);
}

/** Whether the anime exporter can write the document (it writes every property CSS does, and more). */
export function canExportAnime(doc: VectorDoc): AnimeExportCheck {
  const issues: AnimeExportIssue[] = [];
  const { ok, symbol } = addressable(doc);
  let animated = false;
  for (const tr of doc.animations) {
    if (tr.keyframes.length === 0 || tr.property === 'mask' || tr.property === 'clipPath') continue;
    animated = true;
    const at = { layerId: tr.layerId, property: tr.property };
    if (symbol.has(tr.layerId)) issues.push({ code: 'defs_layer', ...at });
    else if (!ok.has(tr.layerId) || ok.get(tr.layerId)!.type === 'raw' || !VECTOR_ID_PATTERN.test(tr.layerId)) issues.push({ code: 'missing_layer', ...at });
    else if (tr.keyframes.some((k) => !valueOk(tr.property, k.value))) issues.push({ code: 'bad_value', ...at });
  }
  if (animated && doc.duration <= 0) issues.push({ code: 'zero_duration' });
  return issues.length === 0 ? { ok: true } : { ok: false, issues };
}

