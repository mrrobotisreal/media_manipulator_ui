const r = (n: number) => Math.round(n * 10) / 10;

export const WORLD_OUTLINE_PATH: string = RINGS.map(
  (ring) => `M${ring.map(([lon, lat]) => `${r(lon + 180)} ${r(90 - lat)}`).join('L')}Z`,
).join('');

export const WORLD_VIEWBOX = { width: 360, height: 180 } as const;

/** Projects lon/lat to viewBox coordinates. */
export function project(lat: number, lon: number): { x: number; y: number } {
  return { x: lon + 180, y: 90 - lat };
}
